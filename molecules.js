const KSHIFT = 'c0-c5>c0-c1 c1-c2>c2-c3 c3-c4>c4-c5';
const donorSteps = D => [`${D}>${D}-c0 c0-c1>c1`, 'c1>c1-c2 c2-c3>c3', 'c3>c3-c4 c4-c5>c5', `c5>c0-c5 ${D}-c0>${D}`, KSHIFT];
const accSteps = (X, Y) => [`c0-c1>c0-${X}` + (Y ? ` ${X}-${Y}>${Y}` : ''), 'c2-c3>c1-c2', 'c4-c5>c3-c4', (Y ? `${Y}>${X}-${Y} ` : '') + `c0-${X}>c0-c5`, KSHIFT];

function benz(extraAtoms, extraBonds, rest) {
  const R = ring('c', 6, -90);
  return Object.assign({atoms: Object.assign({}, R.atoms, extraAtoms), bonds: R.bonds + ' ' + extraBonds, centers: R.centers, d: K1 + (rest.d ? ' ' + rest.d : '')}, rest, {d: K1 + (rest.d ? ' ' + rest.d : '')});
}

