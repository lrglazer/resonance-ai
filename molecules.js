/* Pushing electrons: molecule data.
   Each entry gives the first structure and the arrows; engine.js derives the rest.
   See README.md for the format. */

function ring(pre, n, start, labels = {}) {
  const R = BL / (2*Math.sin(Math.PI/n));
  const atoms = {}, bonds = [];
  for (let i = 0; i < n; i++) {
    const t = (start + 360*i/n) * R2D;
    atoms[pre+i] = [R*Math.cos(t), R*Math.sin(t), labels[i] || ''];
    bonds.push(`${pre}${i}-${pre}${(i+1)%n}@${pre}`);
  }
  return {atoms, bonds: bonds.join(' '), centers: {[pre]: {x:0, y:0}}};
}

function annulene(n, sign) {
  const R = ring('r', n, -90);
  const d = [];
  for (let j = 1; j+1 < n; j += 2) d.push(`r${j}-r${j+1}`);
  const steps = [];
  let k = 0;
  for (let s = 0; s < n; s++) {
    const a = k, b = (k+1)%n, c = (k+2)%n;
    steps.push(sign < 0 ? `r${a}>r${a}-r${b} r${b}-r${c}>r${c}` : `r${b}-r${c}>r${a}-r${b}`);
    k = c;
  }
  return {atoms: R.atoms, bonds: R.bonds, centers: R.centers, d: d.join(' '), q: {r0: sign}, steps};
}

